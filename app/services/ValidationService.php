   public function validar($data, $conductor) {

$vigencia = "desconocida";
$fechaVencimientoCalculada = null;

if (!empty($data['nit_pagador']) && !empty($data['fecha_afiliacion'])) {

    $nit = $data['nit_pagador'];
    $ultimosDos = substr($nit, -2);

    $fecha = new DateTime($data['fecha_afiliacion']);
    $mes = intval($fecha->format("m"));
    $anio = intval($fecha->format("Y"));

    $fechaVencimientoCalculada = $this->fechaVencimientoSegSocial($ultimosDos, $mes, $anio);

    if ($fechaVencimientoCalculada) {
        $hoy = new DateTime();

        if ($hoy > new DateTime($fechaVencimientoCalculada)) {
            $vigencia = "vencida";
        } else {
            $vigencia = "vigente";
        }
    }
}



    // 🔥 1. Validación empresa (IA no detectó nada)
    if (empty($data['nit_pagador']) && empty($data['nombre_empresa'])) {
        return [
            "estado" => "manual",
            "motivo" => "Debe hacer validación manual (empresa no identificada)",
            "vigencia" => $vigencia
        ];
    }

    // 🔥 2. NIT faltante → manual
    if (empty($data['nit_pagador'])) {
        return [
            "estado" => "manual",
            "motivo" => "NIT no detectado",
            "vigencia" => $vigencia
            
        ];
    }

    // 3. Tipo documento
    if ($data['tipo_documento'] === "desconocido") {
        return [
            "estado" => "rechazado",
            "motivo" => "Tipo de documento no válido",
            "vigencia" => $vigencia
        ];
    }

    // 4. Cédula conductor
    if (($data['cc_conductor'] ?? null) != $conductor['cedula']) {
        return [
            "estado" => "rechazado",
            "motivo" => "Cédula no coincide",
            "vigencia" => $vigencia
        ];
    }

    // 5. Fecha
    if (empty($data['fecha_afiliacion'])) {
        return [
            "estado" => "rechazado",
            "motivo" => "Fecha no detectada",
            "vigencia" => $vigencia
        ];
    }

    // 🔥 6. Validación vencimiento PILA
    $nit = $data['nit_pagador'];
    $ultimosDos = substr($nit, -2);

    $fecha = new DateTime($data['fecha_afiliacion']);
    $mes = intval($fecha->format("m"));
    $anio = intval($fecha->format("Y"));

    $fechaVencimiento = $this->fechaVencimientoSegSocial($ultimosDos, $mes, $anio);

    if (!$fechaVencimiento) {
        return [
            "estado" => "manual",
            "motivo" => "No se pudo calcular fecha de vencimiento",
            "vigencia" => $vigencia
        ];
    }

    $hoy = new DateTime();

    if ($hoy > new DateTime($fechaVencimiento)) {
        return [
            "estado" => "rechazado",
            "motivo" => "Planilla vencida (fecha límite: $fechaVencimiento)",
            "vigencia" => $vigencia,
        ];
    }

    

    // ✅ TODO OK
    return [
        "estado" => "aprobado",
        "motivo" => "OK"
    ];
}}
